wb = Workbook()

def sheet(title, headers, widths, rows, start_row=1, example=False, blank_input=0, group_col=None):
    ws = wb.create_sheet(title)
    r0 = start_row
    for j, h in enumerate(headers, 1):
        c = ws.cell(row=r0, column=j, value=h)
        c.font = HDR_FONT; c.fill = HDR_FILL; c.alignment = Alignment(wrap_text=True, vertical="center"); c.border = BORDER
    for j, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(j)].width = w
    r = r0 + 1
    for row in rows:
        is_group = isinstance(row, tuple) and len(row) == 2 and row[0] == "__group__"
        if is_group:
            ws.cell(row=r, column=1, value=row[1]).font = BOLD
            for j in range(1, len(headers) + 1):
                ws.cell(row=r, column=j).fill = GROUP_FILL
                ws.cell(row=r, column=j).border = BORDER
            r += 1; continue
        for j, v in enumerate(row, 1):
            c = ws.cell(row=r, column=j, value=v)
            c.font = EX if example else BODY
            c.alignment = WRAP; c.border = BORDER
        r += 1
    for _ in range(blank_input):
        for j in range(1, len(headers) + 1):
            c = ws.cell(row=r, column=j); c.fill = INPUT_FILL; c.border = BORDER; c.font = BODY; c.alignment = WRAP
        r += 1
    ws.freeze_panes = ws.cell(row=r0 + 1, column=2)
    return ws

